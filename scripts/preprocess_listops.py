"""
scripts/preprocess_listops.py

Converts the ListOps TSV files generated by data/listops.py into PyTorch TensorDatasets saved as .pt files
in data/listops/. These are what train.py loads at runtime.

Usage:
    python3 scripts/preprocess_listops.py
"""

import os
import sys
import csv
import torch
from torch.utils.data import TensorDataset

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW_DIR = os.path.join(ROOT_DIR, "data", "listops_raw")
OUT_DIR = os.path.join(ROOT_DIR, "data", "listops")

# must match seq_len in configs/listops.yaml
SEQ_LEN = 2048

VOCAB = {
    "[PAD]": 0, "[UNK]": 1, "(": 2, ")": 3,
    "MIN": 4, "MAX": 5, "MED": 6, "FIRST": 7, "LAST": 8, "SUM": 9,
    "0": 10, "1": 11, "2": 12, "3": 13, "4": 14, "5": 15,  "6": 16, "7": 17, "8": 18, "9": 19,
}

def tokenise(sequence):
    tokens = [VOCAB.get(t, VOCAB["[UNK]"]) for t in sequence.strip().split()]
    tokens = tokens[:SEQ_LEN]
    pad_len = SEQ_LEN - len(tokens)
    mask = [1] * len(tokens) + [0] * pad_len
    tokens = tokens + [VOCAB["[PAD]"]] * pad_len
    return tokens, mask

def parse_tsv(tsv_path):
    input_ids_list, labels_list, masks_list = [], [], []
    with open(tsv_path, "r") as f:
        reader = csv.DictReader(f, delimiter="\t")
        for row in reader:
            tokens, mask = tokenise(row["Source"])
            label = int(row["Target"])
            input_ids_list.append(tokens)
            labels_list.append(label)
            masks_list.append(mask)
    return TensorDataset(
        torch.tensor(input_ids_list, dtype=torch.long),
        torch.tensor(labels_list, dtype=torch.long),
        torch.tensor(masks_list, dtype=torch.long),
    )

def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    for split in ["train", "test"]:
        tsv_path = os.path.join(RAW_DIR, f"basic_{split}.tsv")
        if not os.path.exists(tsv_path):
            raise FileNotFoundError(f"could not find {tsv_path}. run data/listops.py first")
        
        print(f"parsing {split} split..")
        dataset = parse_tsv(tsv_path)
        save_path = os.path.join(OUT_DIR, f"{split}.pt")
        torch.save(dataset, save_path)
        print(f"saved {len(dataset)} examples to {save_path}")

    print("\ndone - ListOps data ready at data/listops/")


if __name__ == "__main__":
    main()